# Prior Setup
# Define priors centered around the fiducial values from params dictionary
# Sets up prior distributions for each parameter - uniform for H₀, normal for others
prior = pc.Prior([
    uniform(loc=H0_fid-10, scale=20),              # H0 ∈ [H0_fid-10, H0_fid+10]
    norm(loc=ombh2_fid, scale=0.003),              # ombh2
    norm(loc=omch2_fid, scale=0.015),              # omch2
    norm(loc=ns_fid, scale=0.015),                 # ns
    norm(loc=As_fid, scale=3e-10)                  # As
])

# Test likelihood at fiducial values
print("Testing likelihood at fiducial values...")
test_params = [H0_fid, ombh2_fid, omch2_fid, ns_fid, As_fid]
test_loglike = log_likelihood(test_params)
print(f"Log-likelihood at fiducial values: {test_loglike:.2f}")

# Run MCMC (Sampler Execution)
# Runs the MCMC sampling using the PocOMC sampler to explore the posterior distribution
print("Running MCMC...")
sampler = pc.Sampler(
    prior=prior,
    likelihood=log_likelihood,
    vectorize=False,
    random_state=42
)

# Initialize samples as None before running the sampler
samples = None

try:
    # Assuming `sampler` is already set up and ready
    sampler.run()  # Run MCMC sampler
    samples, weights, logl, logp = sampler.posterior()  # Extract posterior samples from the sampler
except Exception as e:
    print(f"An error occurred during sampling: {e}")
    samples = None  # Set samples to None if an error occurs during the sampling

# Check if samples array is empty after running the sampler
if samples is None or len(samples) == 0 or samples.size == 0:
    print("Error: The 'samples' array is empty!")
else:
    # Apply burn-in removal only if the array is not empty
    burn_in = int(0.1 * len(samples))  # Discard first 10% as burn-in (discarding 10% of the chain to ensure reliable inference from the remaining 90%)
    samples = samples[burn_in:]
    weights = weights[burn_in:]
    logl = logl[burn_in:]
    logp = logp[burn_in:]

    print(f"Removed {burn_in} burn-in samples")

