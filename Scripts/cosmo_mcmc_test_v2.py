def compute_realistic_covariance(C_gg, C_gk, C_kg, ell):
    """
    Compute realistic covariance vector for galaxy-CMB cross-correlation.
    Formula used: Cov(C_gg, C_gk) = [C_gk * C_gg + C_gg * C_kg] / (2ℓ + 1)
    Assumes C_kg ≠ C_gk (i.e., not symmetric).
    """
    # Ensure all arrays have the same length
    min_len = min(len(C_gg), len(C_gk), len(C_kg), len(ell))
    C_gg = C_gg[:min_len]
    C_gk = C_gk[:min_len]
    C_kg = C_kg[:min_len]
    ell = ell[:min_len]

    # Compute covariance vector using the specified formula
    cov_diag = (C_gk * C_gg + C_gg * C_kg) / (2 * ell + 1)

    # Add small noise floor to avoid numerical issues
    cov_diag = np.maximum(cov_diag, 1e-10 * np.abs(C_gk * C_kg))

    return cov_diag

